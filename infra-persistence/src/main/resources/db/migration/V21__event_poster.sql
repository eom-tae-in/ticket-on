-- 포스터: 파일 자체는 파일 저장소(infra-storage)에 있고 여기에는 그 파일을 가리키는 열쇠만 둔다(도메인 EventPoster). 열쇠는 추측할 수 없는
--   값 32자 + "." + 그림 형식의 확장자(png · jpg)다 — 누구나 로그인 없이 여는 공개 주소에 그대로 들어간다(주최자 로고 열쇠와 같은 꼴, V16).
--   1단계의 필수 항목이지만 행사를 만든 뒤 따로 올리므로 작성 중에는 비어 있을 수 있다(NULL). 판매를 시작하기 전에 갖췄는지는 판매 시작 직전
--   검증이 본다 — 상태로 막는 CHECK는 두지 않는다.
--   열쇠는 포스터마다 새로 붙으므로 겹치지 않는다(UNIQUE) — 바꾸기 전 포스터의 파일을 지울 때 다른 행사의 포스터가 함께 지워지지 않는다.
--   PostgreSQL의 UNIQUE는 NULL끼리 겹친 것으로 보지 않아, 포스터가 없는 행사는 여럿일 수 있다.
--   바꾸면 이 칸을 새 열쇠로 고치고, 바꾸기 전 포스터의 파일은 커밋된 뒤 지운다. 포스터 변경 이력은 #46이 따로 남긴다.
-- 보관: 행사와 같다.
