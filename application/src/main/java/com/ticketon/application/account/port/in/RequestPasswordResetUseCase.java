package com.ticketon.application.account.port.in;

/**
 * 비밀번호 찾기 — 들어오는 포트. 고른 쪽(관객 계정 / 운영진 로그인)에서 그 이메일로 가입한 계정을 찾아, 비밀번호 찾기를 할 수 있는
 * 계정(로그인할 수 있는 계정)이면 재설정 링크를 메일로 보낸다. 없으면 아무것도 보내지 않는다.
 * <p>
 * <b>부른 쪽에는 무엇을 했는지 알리지 않는다.</b> 계정이 있든 없든, 인증 대기·탈퇴라 보내지 않았든 같은 안내("입력한 이메일로 안내를
 * 보냈습니다")를 해야 한다 — 답이 다르면 이메일을 넣어 보며 가입자를 알아낼 수 있다(docs/01 "같은 이메일로 양쪽 가입", docs/99 D
 * "비밀번호 찾기 안내"). 그래서 돌려주는 값이 없다.
 * <p>
 * <b>응답 시간으로도 드러나지 않게, 들어오는 어댑터는 이 유스케이스를 응답과 떼어(다른 스레드에서) 부른다.</b> 계정이 있을 때만 링크를
 * 저장하고 메일을 보내므로(메일 발송은 바깥 업체 호출이라 오래 걸린다) 응답을 기다리게 하면 걸리는 시간으로 가입 여부가 드러난다.
 * 메일을 보내지 못하면 예외를 던져 새 링크를 되돌리는데, 이 예외도 부른 사람에게 알리지 않고 로그에만 남긴다 — 알리면 계정이 있다는 뜻이 된다.
 * <p>
 * 가입 방법과 상관없이 이메일로 찾는다. OAuth로만 가입한 관객 계정도 이 흐름으로 비밀번호를 정한다(#17이 OAuth 계정을 만든다).
 */
public interface RequestPasswordResetUseCase {

    /**
     * @throws IllegalStateException 재설정 메일을 보내지 못했으면 — 새 링크를 되돌린다
     */
    void requestReset(RequestPasswordResetCommand command);
}
