package com.ticketon.application.event.port.in;

/**
 * 보관 기간이 지난 행사 변경 이력 지우기 — 들어오는 포트. 정해진 시각 작업이 매일 부른다(docs/03 "보관은 행사가 끝난 날부터 6개월", docs/04 "행사가
 * 끝난 뒤 일어나는 일 — 6개월: 제목 · 소개 · 포스터 변경 이력 삭제", docs/99 C "보관 기간").
 * <ul>
 *   <li>대상 — 행사가 끝난 날(취소되지 않은 마지막 회차가 끝난 한국 날짜) + 6개월이 지난 행사. 끝난 날은 행사 상태가 아니라 일정으로 본다.
 *       끝난 날을 알 수 없는 행사(회차가 모두 취소됨 · 마지막 회차의 종료 시각 비움)는 지우지 않는다.</li>
 *   <li>지우는 것 — 그 행사의 제목 · 소개 · 포스터 · 상세 안내 · 지도 링크 · 공개용 연락처 · 회차 출연 이력 전부와, 이력에만 남아 있던 바꾸기 전
 *       포스터 파일(커밋된 뒤). 지금 포스터는 행사와 함께 남는다(docs/99 C "보관 기간" — 일곱 칸 모두 행사 종료 후 6개월).</li>
 *   <li>다시 불러도 안전하다 — 이미 지운 행사는 이력이 없어 대상이 아니다. 하루 빠져도 다음 날 밀린 행사를 지운다.</li>
 * </ul>
 * 지금 시각은 서비스의 시계로 정한다.
 */
public interface PurgeExpiredEventChangeHistoryUseCase {

    /**
     * 행사마다 따로 처리한다 — 한 행사에서 실패해도 나머지 행사는 처리하고, 실패한 행사는 이력이 그대로라 다음에 다시 시도한다.
     *
     * @throws IllegalStateException 처리하지 못한 행사가 있으면 — 나머지를 모두 처리한 뒤 실패한 행사 id와 그 원인을 담아 던진다
     */
    PurgeExpiredEventChangeHistoryResult purgeExpiredChangeHistory();
}
