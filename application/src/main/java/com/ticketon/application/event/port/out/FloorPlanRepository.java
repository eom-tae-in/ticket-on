package com.ticketon.application.event.port.out;

import com.ticketon.domain.event.FloorPlan;
import java.time.Instant;

/**
 * 행사 도면 저장소 — 나가는 포트. 도면은 행사에 하나다(docs/02 "두 개의 축").
 * <p>
 * 구역 · 블록 · 좌석 · 무대 위치를 <b>도면 하나로</b> 읽고 저장한다. 구역 이름과 블록 이름이 겹치지 않는지는 표를 건너 DB가 막을 수 없어, 행사
 * 줄을 잠근 흐름이 도면 하나를 읽고 도메인이 본 뒤 통째로 저장한다.
 * <p>
 * <b>지운 구역 · 블록 · 좌석은 줄을 남긴다.</b> 도면에서 빠진 구역 · 블록은 지운 시각을 적어 두고(블록을 지우면 그 좌석도 같은 시각으로), 다시
 * 읽을 때는 담지 않는다 — 취소 · 회수된 티켓이 원래 구역 · 좌석을 계속 가리킨다(docs/14). 지운 구역 · 블록의 이름은 새 것이 다시 쓸 수 있다.
 * <p>
 * <b>좌석 id는 바뀌지 않는다.</b> 재고 · 티켓 · 검표가 좌석 id를 가리키므로(docs/07, docs/14) 저장된 좌석은 고친 칸만 바뀌고 줄이 다시 만들어지지
 * 않는다 — 블록을 옮기거나 돌리거나 이름을 고쳐도 좌석 id는 그대로다.
 * <p>
 * <b>잠금 — 행사 줄 다음이다.</b> 도면을 읽고 고쳐 저장하는 흐름은 먼저 행사 줄을 FOR UPDATE로 잠근다({@link EventRepository#findByIdForUpdate}).
 * 같은 행사의 도면 저장은 행사 줄에서 차례로 처리되므로 도면의 줄은 따로 잠그지 않는다.
 * <p>
 * <b>도면은 여러 문장으로 읽는다.</b> 행사 줄을 잠그지 않고 읽는 조회는 트랜잭션 전체를 스냅숏 하나로 읽어야 한다(REPEATABLE READ) — 문장마다 새
 * 스냅숏을 잡으면(READ COMMITTED) 그 사이에 커밋된 편집을 반쯤만 읽어 도면을 되살리지 못한다(좌석 없는 블록, 도면에 없는 구역을 가리키는 좌석).
 */
public interface FloorPlanRepository {

    /**
     * 그 행사의 도면을 읽는다 — 지우지 않은 구역(더한 순서) · 블록(얹은 순서)과 그 좌석(행 · 번호 순서), 무대 위치. 아무것도 없으면 빈 도면이다.
     * 행사가 있는지는 보지 않는다 — 부르는 쪽이 행사를 먼저 찾는다. 행사 줄을 잠근 뒤에 부르거나, 스냅숏 하나(REPEATABLE READ)인 트랜잭션에서
     * 부른다.
     */
    FloorPlan findByEventId(long eventId);

    /**
     * 도면을 저장한다 — 도면에서 빠진(지금 표에서 지우지 않은) 구역 · 블록과 그 블록의 좌석에 지운 시각을 적고, 저장된 구역 · 블록 · 좌석은 지금
     * 값으로 쓰고(좌석은 구역 · 속성 · 활성만 — 번호는 바뀌지 않는다), 새 구역 · 블록(id 없음)과 새 블록의 좌석은 넣는다. 무대 위치를 정했으면
     * 지금 값으로 쓴다. 구역 종류 · 블록 크기는 바꾸지 않는다. 구역을 지운 도면이면 도메인이 푼 좌석 배정이 같은 저장에서 쓰인다.
     *
     * @param floorPlan {@link #findByEventId}로 읽어 고친 도면
     * @param now       도면에서 빠진 구역 · 블록 · 좌석에 적을 지운 시각
     * @return 새 구역 · 블록 · 좌석에 id가 붙은 도면 — 구역 · 블록은 더한 순서
     * @throws IllegalArgumentException 표에 없거나 지운 구역 · 블록 · 좌석, 다른 행사의 것, 종류가 바뀐 구역, 크기가 바뀐 블록, 다른 블록의 좌석,
     *                                  번호가 바뀐 좌석을 저장하려 하면 — 아무것도 쓰지 않는다
     */
    FloorPlan save(FloorPlan floorPlan, Instant now);
}
