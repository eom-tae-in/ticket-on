package com.ticketon.application.admin.query;

/**
 * 관리자 처리 목록에 쌓이는 요청의 종류(docs/13 "5. 플랫폼 관리자 — 처리 목록", docs/12 "관리자 대상").
 * <p>
 * 관리자는 알림 대신 처리 목록으로 일을 받는다. 지금은 주최자 신청 · 소유자 변경 · 소유자 이전 신청 · 주최자명 변경 · 정산 계좌 · 사업자 정보
 * 변경 확인이 있고, 다시 열기 신청 ·
 * 연기·장소 변경 승인 · QR 재발행 · 신고 · 불가항력 확인 등은 그 기능을 만드는 이슈가 종류를 더하고, 처리 목록 조회(원천 표)와 강조 기준을 함께
 * 더한다.
 * 이 이름은 화면 타입의 이름이 되므로 바꾸지 않는다.
 */
public enum AdminWorkKind {

    /** 주최자 신청 — 심사 중인 새 주최자 신청서. 대상은 신청서다. 심사 목표일이 다가오면 강조한다. */
    ORGANIZER_APPLICATION,

    /**
     * 소유자 변경(사후 확인) — 소유자가 운영자에게 넘긴 한 건으로 아직 관리자가 확인하지 않은 것(docs/12 "소유자가 바뀌면 관리자에게도
     * 알립니다"). 대상은 소유자 변경 이력이다. 관리자를 거치지 않고 이미 바뀐 일이라 기한이 없어 강조하지 않는다. 확인하면 목록에서 빠진다.
     * 관리자가 소유자 이전 신청을 승인해 바꾼 건은 쌓이지 않는다.
     */
    OWNERSHIP_CHANGE,

    /**
     * 소유자 이전 신청 — 소유자와 연락이 끊겨 운영자가 낸 신청으로 아직 심사 중인 것(docs/12 "관리자 대상 — 소유자 이전 신청", docs/13 "처리
     * 목록 — 소유자 이전 신청"). 대상은 신청이다. 문서에 정한 처리 기한이 없어 강조하지 않는다. 승인 · 반려하면 목록에서 빠진다.
     */
    OWNERSHIP_CLAIM,

    /**
     * 주최자명 변경(사후 확인) — 소유자가 주최자명을 바꾼 한 건으로 아직 관리자가 확인하지 않은 것(docs/12 "관리자 대상 — 주최자명 변경 (사후
     * 확인용. 사칭이면 신고·정지로 처리)", docs/13 "처리 목록 — 주최자명 변경 (사후 확인)"). 대상은 주최자명 변경 이력이다. 관리자를 거치지 않고
     * 이미 바뀐 일이라 기한이 없어 강조하지 않는다. 확인하면 목록에서 빠진다.
     */
    ORGANIZER_NAME_CHANGE,

    /**
     * 정산 계좌 · 사업자 정보 변경 확인 — 소유자가 낸 변경 요청으로 아직 확인 중인 것(docs/12 "관리자 대상 — 정산 계좌 변경 확인", docs/13 "처리
     * 목록 — 정산 계좌 · 사업자 정보 변경 확인"). 대상은 변경 요청이다. 문서에 정한 처리 기한이 없어 강조하지 않는다. 승인 · 반려하면 목록에서
     * 빠진다. 확인 중에는 기존 값이 그대로 쓰인다.
     */
    ORGANIZER_CHANGE_REQUEST
}
