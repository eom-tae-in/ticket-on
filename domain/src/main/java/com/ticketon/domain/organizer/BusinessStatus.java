package com.ticketon.domain.organizer;

/**
 * 사업자 여부 — 신청서의 필수 항목. 판매자 정보를 어떻게 보여 줄지가 여기서 갈린다(docs/01 "신청 항목", "통신판매중개자 의무").
 * <p>
 * 사업자는 상호 · 대표자 · 사업장 주소 · 사업장 전화번호 · 사업자등록번호를 행사 페이지 "판매자 정보"에 공개한다. 비사업자(개인 · 동아리 ·
 * 동호회)는 주최자명과 안내 문구만 나가고, 우리가 이름 또는 단체명 · 담당자 연락처를 확인해 둔다(docs/01 "판매자 정보").
 * 이 이름은 저장소에 그대로 남으므로 바꾸지 않는다.
 */
public enum BusinessStatus {

    /** 사업자 — 사업자 항목이 필수다. */
    BUSINESS,

    /** 비사업자 — 사업자 항목을 받지 않는다. 사업자등록번호는 개인 주최자에게 없다. */
    NON_BUSINESS
}
