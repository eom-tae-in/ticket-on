package com.ticketon.domain.organizer;

import com.ticketon.domain.error.ErrorCode;

/**
 * 주최자 도메인의 오류 코드. 문구는 화면에 그대로 나간다.
 */
public enum OrganizerErrorCode implements ErrorCode {

    /**
     * 사업자라고 했는데 사업자 항목(상호 · 대표자 성명 · 사업장 주소 · 사업장 전화번호 · 사업자등록번호) 중 빠진 것이 있다 — 사업자만 필수다
     * (docs/01 "신청 항목"). 어느 항목이 빠졌는지는 예외의 detail에 적는다.
     */
    BUSINESS_INFORMATION_MISSING("사업자는 상호 · 대표자 성명 · 사업장 주소 · 사업장 전화번호 · 사업자등록번호를 모두 입력해 주세요."),

    /**
     * 비사업자라고 했는데 사업자 항목을 적었다. 사업자 항목은 행사 페이지 "판매자 정보"에 그대로 나가는 값이라(docs/01 "판매자 정보 — 사업자는
     * 공개, 비사업자는 확인만") 사업자 여부와 어긋난 값을 받아 두지 않는다.
     */
    BUSINESS_INFORMATION_FOR_NON_BUSINESS("비사업자는 사업자 정보를 입력하지 않습니다. 사업자 여부를 확인해 주세요."),

    /**
     * 이미 승인 또는 반려한 신청서를 다시 처리하려 했다. 반려된 뒤에는 새로 신청한다(docs/01 "반려 — 재신청은 제한 없이 허용").
     * 두 관리자가 같은 신청을 거의 동시에 승인·반려해 한쪽이 먼저 처리한 경우도 이 코드다.
     */
    APPLICATION_ALREADY_REVIEWED("이미 심사를 마친 신청입니다."),

    /** 없는 주최자 신청을 보거나 처리하려 했다. */
    APPLICATION_NOT_FOUND("주최자 신청을 찾을 수 없습니다."),

    /**
     * 심사 중인 신청이 있는데 새 신청서를 내려 했다 — 승인 전까지 로그인하면 "심사 중" 화면만 보인다(docs/01 "주최자 신청과 승인").
     * 반려된 뒤에는 제한 없이 다시 낸다(docs/01 "반려"). 같은 사람이 거의 동시에 두 번 내 한쪽이 먼저 저장된 경우도 이 코드다.
     */
    APPLICATION_ALREADY_UNDER_REVIEW("심사 중인 신청이 있습니다. 심사 결과를 기다려 주세요."),

    /**
     * 신청한 운영진 로그인이 탈퇴한 신청서를 승인하려 했다 — 승인하면 신청한 사람이 소유자가 되는데, 탈퇴한 계정은 로그인할 수 없어 배상과 정산
     * 계좌를 책임질 사람이 없다(docs/01 "소유자는 1명입니다 … 책임질 사람이 분명해야"). 반려는 할 수 있다. 심사 중에 탈퇴하는 일을 어떻게 다룰지
     * (탈퇴를 막을지, 신청을 거둘지)는 문서에 없어 확인 과제로 남기고, 그때까지 승인만 막는다.
     */
    APPLICANT_WITHDRAWN("신청한 운영진 로그인이 탈퇴해 승인할 수 없습니다. 반려해 주세요."),

    /** 심사 중이 아닌 주최자를 승인하려 했다. 승인은 심사 중인 주최자를 활동으로 바꾸는 일이다. */
    ORGANIZER_NOT_UNDER_REVIEW("심사 중인 주최자가 아닙니다."),

    /**
     * 활동 중이 아닌 주최자(심사 중 · 닫힘 · 영구 정지)에서 운영 일을 하거나 그 정보를 바꾸려 했다. 주최자는 승인된 뒤에야 운영하고, 닫히거나
     * 영구 정지된 주최자에는 운영진이 남지 않는다(docs/01 "탈퇴와 주최자 닫기", "정지 4단계"). 운영진 권한 확인
     * ({@link StaffPermission#check})에서는 권한 없음으로, 주최자 정보 변경 · 소유자 이전 신청 승인에서는 규칙 위반으로 막는다.
     */
    ORGANIZER_NOT_ACTIVE("활동 중인 주최자가 아닙니다."),

    /**
     * 그 주최자에 지금 소속된 운영진이 아니다 — 소속된 적이 없거나 이미 나왔다. 나온 주최자의 정산·현황은 볼 수 없다
     * (docs/01 "운영진 프로필 — 지난 소속"). 권한 없음으로 막는다.
     */
    NOT_ORGANIZER_STAFF("이 주최자의 운영진이 아닙니다."),

    /**
     * 운영자가 소유자만 하는 일({@link StaffAction#isOwnerOnly})을 하려 했다 — 배상·정산 계좌·운영진 관리처럼 책임질 사람이 분명해야 하는
     * 일이다(docs/01 "권한 두 가지"). 권한 없음으로 막는다.
     */
    OWNER_ONLY_ACTION("소유자만 할 수 있는 일입니다."),

    /** 이미 그 주최자에 소속된 사람을 운영자로 다시 들이려 했다. 한 사람은 한 주최자에 한 역할로만 소속된다. */
    ALREADY_ORGANIZER_STAFF("이미 이 주최자의 운영진입니다."),

    /**
     * 그 주최자의 운영자가 아닌 사람에게 소유자를 넘기려 했다 — <b>이미 그 주최자의 운영자인 사람만</b> 받을 수 있고 바깥 사람에게 바로 넘길 수
     * 없다. 바깥 사람이면 먼저 운영자로 초대한다(docs/01 "소유자 넘기기", docs/11 "대표가 바뀔 때"). 운영자로 들어온 사람만 받게 해 소유자
     * 자리를 가로채기 어렵게 한다(docs/01 "가로채기를 막는 장치").
     */
    OWNERSHIP_RECEIVER_NOT_OPERATOR("소유자는 이 주최자의 운영자에게만 넘길 수 있습니다. 바깥 사람이면 먼저 운영자로 초대해 주세요."),

    /**
     * 소유자를 넘기려 했는데 그 사이 넘기는 사람의 소유자 소속이 먼저 끝났다 — 같은 소유자가 거의 동시에 두 번 넘겨 한쪽이 먼저 저장된 경우다.
     * 소유자는 언제나 1명이라(docs/01 "소유자는 1명입니다") 두 넘기기 가운데 하나만 남는다. 소유자 넘기기 저장이 진 쪽이 받는다.
     * <p>
     * 관리자가 소유자 이전 신청을 승인하려 했는데 신청 뒤 소유자가 이미 바뀐 경우도 이 코드다 — 신청은 그때의 소유자(연락이 끊겼다는 그 사람)를
     * 가리키므로({@link OwnershipClaim}), 그 사람이 돌아와 직접 넘겼거나 다른 신청이 먼저 승인됐으면 이 신청으로는 바꾸지 않고 반려한다.
     */
    OWNERSHIP_ALREADY_TRANSFERRED("이미 소유자가 바뀌었습니다."),

    /** 없는 소유자 변경 이력을 관리자가 확인하려 했다. */
    OWNERSHIP_CHANGE_NOT_FOUND("소유자 변경 기록을 찾을 수 없습니다."),

    /**
     * 이미 확인한 소유자 변경을 관리자가 다시 확인하려 했다. 확인은 한 번이다({@link OwnershipChange#confirm}). 두 관리자가 거의 동시에 같은
     * 변경을 확인해 한쪽이 먼저 처리한 경우도 이 코드다.
     */
    OWNERSHIP_CHANGE_ALREADY_CONFIRMED("이미 확인한 소유자 변경입니다."),

    /**
     * 관리자가 소유자 이전 신청을 승인해 바꾼 소유자 변경을 사후 확인하려 했다. 사후 확인은 관리자를 거치지 않은 소유자 넘기기만 받는다 —
     * 신청 승인은 관리자가 확인한 뒤 바꾼 것이라 처리 목록 '소유자 변경'에 쌓이지 않는다({@link OwnershipChangeMethod#CLAIM_APPROVAL}).
     */
    OWNERSHIP_CHANGE_NOT_CONFIRMABLE("소유자 이전 신청을 승인해 바꾼 소유자 변경은 따로 확인하지 않습니다."),

    /** 없는 주최자명 변경 이력을 관리자가 확인하려 했다. */
    ORGANIZER_NAME_CHANGE_NOT_FOUND("주최자명 변경 기록을 찾을 수 없습니다."),

    /**
     * 이미 확인한 주최자명 변경을 관리자가 다시 확인하려 했다. 확인은 한 번이다({@link OrganizerNameChangeEntry#confirm}). 두 관리자가 거의
     * 동시에 같은 변경을 확인해 한쪽이 먼저 처리한 경우도 이 코드다.
     */
    ORGANIZER_NAME_CHANGE_ALREADY_CONFIRMED("이미 확인한 주최자명 변경입니다."),

    /**
     * 소유자가 소유자 이전을 신청하려 했다 — 이전 신청은 소유자와 연락이 끊겨 넘겨줄 사람이 없을 때 운영자가 하는 것이다(docs/01 "소유자와
     * 연락이 끊긴 경우", docs/13 "소유자 이전 신청 ※ 운영자"). 소유자는 운영자에게 직접 넘긴다.
     */
    OWNER_CANNOT_CLAIM_OWNERSHIP("소유자는 이전 신청 없이 운영자에게 직접 넘길 수 있습니다."),

    /**
     * 같은 주최자에 심사 중인 소유자 이전 신청을 이미 냈는데 또 내려 했다 — 결과를 기다린다. 같은 사람이 거의 동시에 두 번 내 한쪽이 먼저 저장된
     * 경우도 이 코드다. 다른 운영자의 신청과는 상관없다.
     */
    OWNERSHIP_CLAIM_ALREADY_UNDER_REVIEW("심사 중인 소유자 이전 신청이 있습니다. 심사 결과를 기다려 주세요."),

    /** 없는 소유자 이전 신청을 관리자가 보거나 처리하려 했다. */
    OWNERSHIP_CLAIM_NOT_FOUND("소유자 이전 신청을 찾을 수 없습니다."),

    /**
     * 이미 승인 또는 반려한 소유자 이전 신청을 다시 처리하려 했다. 두 관리자가 같은 신청을 거의 동시에 승인·반려해 한쪽이 먼저 처리한 경우도 이
     * 코드다.
     */
    OWNERSHIP_CLAIM_ALREADY_REVIEWED("이미 심사를 마친 소유자 이전 신청입니다."),

    /**
     * 소유자 이전 신청을 승인하려 했는데 신청한 사람이 그 주최자의 운영자가 아니다 — 신청 뒤 나갔거나 내보내졌거나 운영진 로그인을 탈퇴했다.
     * 소유자는 기존 운영자에게만 넘어간다(docs/01 "가로채기를 막는 장치"). 탈퇴한 계정은 로그인할 수 없어 책임질 사람이 될 수 없다. 반려는 할 수
     * 있다.
     */
    CLAIMANT_NOT_OPERATOR("신청한 사람이 이 주최자의 운영자가 아니어서 승인할 수 없습니다. 반려해 주세요."),

    /** 그 주최자의 운영자가 아닌 사람을 내보내려 했다. 소유자는 내보낼 수 없다 — 먼저 소유자를 넘긴다. */
    NOT_AN_OPERATOR("이 주최자의 운영자가 아닙니다."),

    /**
     * 소유자가 주최자에서 나가거나 운영진 로그인을 탈퇴하려 했다 — 소유자는 언제나 1명이라 먼저 소유자를 넘기거나 주최자를 닫아야 한다
     * (docs/01 "탈퇴와 주최자 닫기"). 운영자는 언제든 나갈 수 있다.
     */
    OWNER_MUST_HAND_OVER_FIRST("먼저 소유자를 넘기거나 주최자를 닫아야 합니다."),

    /**
     * 그 사람의 소속을 끝내려 했는데 그 사이 이미 끝났다 — 소유자가 내보내는 사이 그 운영자가 스스로 나갔거나, 두 요청이 거의 동시에 같은 사람을
     * 내보낸 경우다. 소속을 끝내는 저장이 진 쪽이 받는다.
     */
    MEMBERSHIP_ALREADY_ENDED("이미 운영진에서 빠졌습니다."),

    /**
     * 없는 운영자 초대이거나, 로그인한 운영진의 이메일로 온 초대가 아니다. 초대는 초대받은 이메일의 운영진 로그인만 답한다(docs/01 "운영자
     * 초대"). 남의 초대가 있는지도 알려 주지 않으려고 없는 초대와 같게 답한다.
     */
    STAFF_INVITATION_NOT_FOUND("받은 초대를 찾을 수 없습니다."),

    /**
     * 같은 이메일로 보낸 초대가 아직 답을 기다리고 유효 기간도 남아 있다. 한 주최자가 한 이메일로 기다리는 초대는 하나뿐이다. 유효 기간이 지난
     * 초대는 다시 초대하면 다시 열린다({@link StaffInvitation#reinvite}). 같은 이메일로 거의 동시에 두 번 초대해 한쪽이 먼저 저장된 경우도
     * 이 코드다.
     */
    STAFF_INVITATION_ALREADY_PENDING("이미 초대를 보낸 이메일입니다. 받은 분의 답을 기다려 주세요."),

    /** 이미 수락하거나 거절한 초대에 다시 답하려 했다. 같은 초대를 거의 동시에 두 번 수락해 한쪽이 먼저 처리된 경우도 이 코드다. */
    STAFF_INVITATION_ALREADY_ANSWERED("이미 답한 초대입니다."),

    /** 유효 기간({@link com.ticketon.domain.policy.ProposedPolicy#STAFF_INVITATION_VALIDITY})이 지난 초대에 답하려 했다. */
    STAFF_INVITATION_EXPIRED("유효 기간이 지난 초대입니다. 소유자에게 다시 초대해 달라고 요청해 주세요."),

    /**
     * 운영진 프로필이 없다 — 없는 운영진 로그인이거나, 주최자에 소속된 적이 없어 아직 운영진이 아니거나, 탈퇴했다({@link StaffPublicProfile#of}).
     * 공개 페이지라 어느 경우인지 가려 알려 주지 않는다 — 누가 운영진 로그인을 만들었는지, 탈퇴했는지가 드러나지 않게.
     */
    STAFF_PROFILE_NOT_FOUND("운영진 프로필을 찾을 수 없습니다."),

    /**
     * 공개 주소로 연 로고 파일이 없다 — 로고 열쇠의 꼴이 아니거나, 바꾸거나 지워 파일이 없어졌다. 공개 주소라 어느 경우인지 가려 알려 주지
     * 않는다.
     */
    ORGANIZER_LOGO_NOT_FOUND("로고를 찾을 수 없습니다.");

    private final String message;

    OrganizerErrorCode(String message) {
        this.message = message;
    }

    @Override
    public String message() {
        return message;
    }
}
