package com.ticketon.domain.organizer;

/**
 * 주최자 상태 — 심사 중 / 활동 / 닫힘 / 영구 정지(docs/14 "전체 관계도").
 * <p>
 * <b>닫혀도 지우지 않는다.</b> 닫힌 주최자는 "닫힘"으로 남아 행사·취소·정지·정산 이력을 전부 보존하고, 다시 열면 이어진다
 * (docs/01 "탈퇴와 주최자 닫기", docs/11 "데이터 보관").
 * <p>
 * 저장하는 것은 이 넷뿐이다. 정지 1~3단계(신규 개설 차단 · 판매 중단 · 전원 환불)는 주최자 상태가 아니라 주최자에 걸리는 정지 기록이다 —
 * 정지 중에도 주최자는 활동 상태이고 이미 판매 중인 행사는 그대로다(docs/01 "정지 4단계"). 주최자 페이지의 "활동 종료" 배지도 저장하지
 * 않고 닫힘 상태에서 계산한다.
 * <p>
 * 이 이름은 저장소에 그대로 남으므로 바꾸지 않는다.
 */
public enum OrganizerStatus {

    /** 심사 중 — 신청을 받았고 아직 승인되지 않았다. 행사를 열 수 없다. */
    UNDER_REVIEW,

    /** 활동 — 승인되어 운영진이 행사를 열고 운영한다. */
    ACTIVE,

    /** 닫힘 — 소유자가 닫았다. 운영진은 전원 빠지고 새 행사를 열 수 없다. 주최자 페이지·지난 행사 페이지는 "활동 종료" 배지로 남는다. */
    CLOSED,

    /** 영구 정지 — 정지 4단계. 주최자 페이지가 내려가고 운영진 프로필의 참여 목록에서도 빠진다. */
    PERMANENTLY_SUSPENDED
}
