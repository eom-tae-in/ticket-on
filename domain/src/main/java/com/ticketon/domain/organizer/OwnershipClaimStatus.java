package com.ticketon.domain.organizer;

/**
 * 소유자 이전 신청 상태 — 운영자가 신청하고 관리자가 확인한 뒤 승인하거나 사유를 붙여 반려한다(docs/01 "소유자 넘기기 — 소유자와 연락이 끊긴
 * 경우", docs/11 "대표가 바뀔 때").
 * <p>
 * 이 이름은 저장소에 그대로 남으므로 바꾸지 않는다.
 */
public enum OwnershipClaimStatus {

    /** 심사 중 — 신청했고 관리자가 아직 처리하지 않았다. 관리자 처리 목록에 '소유자 이전 신청'으로 남아 있다. */
    UNDER_REVIEW,

    /** 승인 — 신청한 운영자가 소유자가 됐고 신청 때의 소유자는 운영자로 남았다. */
    APPROVED,

    /** 반려 — 사유를 남기고 운영진에게 알렸다. 소유자는 그대로다. */
    REJECTED
}
