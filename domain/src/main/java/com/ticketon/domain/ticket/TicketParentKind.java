package com.ticketon.domain.ticket;

/**
 * 티켓의 부모 종류 — 예매 건 또는 초대권(docs/14 "티켓의 부모 — 예매 건과 초대권").
 * <p>
 * 둘 다 여러 장을 함께 발권해 한 목록에서 나눠 주지만 돈이 다르다. 예매 건은 결제 · 환불이 있고, 초대권은 결제가 없어 회수만 한다(docs/08
 * "초대권"). 그래서 결제 금액 · 적용 할인 · 공제 면제 · 배상 · 회차별 포기 · 부분 환불은 예매 티켓에만 있다.
 * <p>
 * 이 이름은 저장소에 그대로 남으므로 바꾸지 않는다.
 */
public enum TicketParentKind {

    /** 예매 건 — 관객이 결제한 단위(예매번호). */
    BOOKING,

    /** 초대권 — 주최자가 결제 없이 발권한 묶음(초대권 번호). */
    INVITATION
}
