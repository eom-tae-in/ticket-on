package com.ticketon.domain.event;

/**
 * 판매를 멈춘 까닭 — 주최자가 멈췄는지, 관리자 조치(정지 2단계 · 페이지 내리기)로 멈췄는지(docs/04 "판매 중단", docs/01 "관리자가 멈춘 판매는
 * 주최자가 풀 수 없습니다").
 * <p>
 * <b>관리자 조치로 멈춘 동안은 주최자가 재개할 수 없다.</b> 조치가 풀려도 판매는 저절로 열리지 않는다 — 관리자가 멈추기 전에 주최자가 이미 멈춰
 * 뒀을 수 있어, 저절로 열면 주최자가 닫아 둔 판매가 모르는 사이 열린다(docs/99 B "해제 시 판매 자동 재개"). 그래서 관리자 조치는 저마다 걸고
 * 풀며({@link Event#holdSales}, {@link Event#releaseSalesHold}), 정지와 페이지 내리기가 함께 걸려 있으면 둘 다 풀려야 주최자가 재개한다.
 * <p>
 * 이 이름은 저장소에 그대로 남으므로 바꾸지 않는다.
 */
public enum SalesPauseCause {

    /** 주최자 — 운영진이 사정이 생겨 잠시 멈췄다. 한 줄 사유를 적을 수 있다. 운영진이 다시 연다. */
    ORGANIZER,

    /** 정지 2단계 — 관리자가 주최자를 정지하며 고른 행사의 판매를 멈췄다(docs/01 "정지 4단계"). 정지를 풀면 조치가 풀린다. */
    ADMIN_SUSPENSION,

    /** 페이지 내리기 — 관리자가 행사 페이지를 내렸다. 페이지 없이는 예매할 수 없다(docs/01 "행사 페이지 내리기"). 다시 올리면 조치가 풀린다. */
    ADMIN_PAGE_TAKEDOWN;

    /** 관리자 조치인지 — 정지 2단계 · 페이지 내리기. */
    public boolean isAdminAction() {
        return this != ORGANIZER;
    }
}
