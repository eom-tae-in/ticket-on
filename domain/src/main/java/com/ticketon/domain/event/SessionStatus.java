package com.ticketon.domain.event;

/**
 * 회차 상태 — 시간이 정하는 회차 하나의 상태(docs/04 "행사 상태와 회차 상태는 다릅니다"). <b>저장하지 않고 계산한다</b>
 * ({@link SessionTimes#status}) — 저장하면 정해진 시각마다 바꿔 줘야 하고, 그 작업이 한 번 실패하면 끝난 회차가 판매 중으로 남는다
 * (docs/14 "저장하는 것과 계산하는 것").
 * <p>
 * 8회차 공연에서 3회차는 끝났고 5회차는 남았다면 행사는 여전히 판매 중이다. 행사 상태는 행사가, 회차 상태는 회차마다 따로 본다.
 * <ul>
 *   <li>회차 상태는 <b>시간만</b> 본다. 예매가 열렸는지(오픈 시각), 판매를 멈췄는지는 행사 상태가 본다.</li>
 *   <li>회차를 취소했는지는 회차 상태와 따로 갖는다({@link EventSession#isCancelled}). 취소된 회차는 시간이 남아 있어도 팔지 않는다.</li>
 * </ul>
 */
public enum SessionStatus {

    /** 판매 중 — 그 회차의 예매 종료 시각 전. */
    ON_SALE,

    /** 판매 종료 — 그 회차의 예매 종료 시각이 지났고 회차는 아직 끝나지 않았다. 종료 시각을 비워 둔 회차는 끝났는지 알 수 없어 여기 머문다. */
    SALES_CLOSED,

    /** 종료 — 그 회차가 끝났다(회차형은 종료 시각, 종일형은 운영 종료가 지났다). */
    ENDED
}
