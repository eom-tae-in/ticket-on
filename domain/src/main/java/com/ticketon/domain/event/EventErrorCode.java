package com.ticketon.domain.event;

import com.ticketon.domain.error.ErrorCode;

/**
 * 행사 도메인의 오류 코드. 문구는 화면에 그대로 나간다.
 */
public enum EventErrorCode implements ErrorCode {

    /**
     * 고른 유형의 목록에 없는 카테고리다 — 다른 유형의 카테고리(공연에 "회화")이거나 아직 정식 카테고리가 아닌 이름이다. 카테고리는 유형을 고르면
     * 그에 맞는 목록에서 고른다(docs/03 "카테고리"). 목록에 없는 장르는 "기타"를 고르고 장르명으로 적는다.
     */
    EVENT_CATEGORY_NOT_IN_TYPE("고른 유형에서 쓸 수 없는 카테고리입니다. 카테고리를 다시 골라 주세요."),

    /** "기타"를 골랐는데 장르명을 적지 않았다 — 기타는 장르명을 자유 입력받는다(docs/03 "카테고리"). */
    EVENT_GENRE_NAME_REQUIRED("카테고리 '기타'를 고르면 장르명을 입력해 주세요."),

    /**
     * 정식 카테고리를 골랐는데 장르명을 적었다. 장르명은 "기타"를 고를 때만 받는다(docs/03 "카테고리") — 관리자가 승격할 장르를 고르는 '기타'
     * 장르명 목록에 정식 카테고리 행사의 값이 섞이지 않게, 고른 카테고리와 어긋난 값을 받아 두지 않는다.
     */
    EVENT_GENRE_NAME_ONLY_FOR_OTHER("장르명은 카테고리 '기타'를 고를 때만 입력합니다."),

    /**
     * 암호 보호로 두는데 암호가 없다 — 새로 적지 않았고 걸려 있던 암호도 없다. 암호 보호는 링크와 암호를 함께 알아야 연다(docs/03 "공개 수준
     * 3단계"). 이미 암호 보호인 행사는 새로 적지 않으면 걸려 있던 암호를 그대로 쓴다({@link EventVisibilitySetting#change}).
     */
    EVENT_PASSWORD_REQUIRED("암호 보호 행사는 암호를 입력해 주세요."),

    /**
     * 조정한 취소 규정이 어느 날이라도 기준(소비자분쟁해결기준)보다 공제율이 높다. 규정은 기준을 처음 값으로 고정하고 관객에게 더 유리한 쪽으로만
     * 조정한다 — "7일 전부터 환불 불가"는 막는다(docs/08 "규정은 기준 고정, 관대한 방향만 조정 가능", {@link CancellationPolicy}).
     */
    CANCELLATION_POLICY_STRICTER_THAN_STANDARD("취소 규정은 기준보다 관객에게 불리하게 정할 수 없습니다. 모든 구간의 공제율을 기준 이하로 정해 주세요."),

    /**
     * 종일형 행사에 시간을 정한 회차를 더하려 했다. 종일형은 날짜 아래 회차가 하나이고 시간대 분할이 없다 — 시간을 쪼개려면 회차형으로 등록한다
     * (docs/02 "시간을 쪼개려면 회차형으로 등록합니다", docs/99 B "종일형 시간대 분할").
     */
    ALL_DAY_SINGLE_SESSION_PER_DATE("종일형은 날짜마다 회차가 하나입니다. 시간대를 나누려면 회차 방식을 회차형으로 골라 주세요."),

    /** 종일형 행사에 이미 있는 날짜를 또 더하려 했다 — 종일형은 날짜가 곧 회차 하나다. 취소된 날짜도 남아 있어 다시 더할 수 없다. */
    SCHEDULE_DATE_ALREADY_EXISTS("이미 추가한 날짜입니다."),

    /**
     * 회차형 행사의 같은 날짜에 시작 시각이 같은 회차가 이미 있다. 도면이 행사에 하나라(docs/02) 같은 시각의 회차 둘은 관객에게 같은 회차로
     * 보인다. 취소된 회차도 남아 있어 그 시각에는 다시 만들 수 없다.
     */
    SESSION_START_TIME_TAKEN("같은 날짜에 같은 시각에 시작하는 회차가 이미 있습니다."),

    /**
     * 날짜가 있는데 회차 방식을 바꾸려 했다. 회차형 회차는 시작 · 종료를, 종일형 회차는 그날의 운영 시간을 시간으로 가져 한쪽에서 다른 쪽으로
     * 옮길 기준이 문서에 없다. 날짜를 모두 지운 뒤 바꾼다.
     */
    SESSION_MODE_LOCKED_BY_DATES("회차 방식을 바꾸려면 먼저 날짜를 모두 지워 주세요."),

    /**
     * 종료 시각을 '입력'하려 했는데 이미 입력돼 있다. 시간 수정이 잠긴 뒤에도 비어 있던 종료 시각을 채우는 것만은 받지만(docs/02 "회차의 시간
     * 정보"), 이미 있는 종료 시각을 바꾸는 것은 회차 시간 수정이다.
     */
    SESSION_END_TIME_ALREADY_ENTERED("이미 종료 시각이 입력된 회차입니다."),

    /** 이 행사의 일정에 없는 회차다. */
    SESSION_NOT_FOUND("회차를 찾을 수 없습니다."),

    /** 이 행사의 일정에 없는 날짜다. */
    SCHEDULE_DATE_NOT_FOUND("날짜를 찾을 수 없습니다."),

    /**
     * 같은 도면에 같은 이름의 블록이 이미 있다. 블록은 좌석 번호를 유일하게 만드는 단위라, 이름이 같으면 양쪽에 같은 "1층 12열 7번"이 생긴다
     * (docs/02 "블록 — 중복 검증을 겁니다"). 이름은 앞뒤 공백을 걷고 NFC로 맞춘 값끼리 견준다.
     */
    BLOCK_NAME_ALREADY_TAKEN("이미 있는 블록 이름입니다. 다른 이름을 입력해 주세요."),

    /**
     * 블록 이름이 같은 도면의 구역 이름과 겹친다 — 블록 이름은 구역 이름(R석, S석)과 겹칠 수 없다(docs/02 "블록"). 문서 문구는
     * "'R석'은 이미 구역 이름으로 쓰고 있습니다. 다른 이름을 입력해 주세요."인데, 오류 문구는 고정 문구라 이름을 넣지 못해 뺐다(확인 필요, #37).
     */
    BLOCK_NAME_TAKEN_BY_ZONE("이미 구역 이름으로 쓰고 있습니다. 다른 이름을 입력해 주세요."),

    /**
     * 확인 필요 (#37) — 같은 도면에 같은 이름의 구역이 이미 있다. 스탠딩 구역이 여럿이면 구역 이름으로 나누고(docs/02 "설정 흐름") 수량형 티켓은
     * 구역 이름으로 구역을 가리키므로("스탠딩A · 0091-2") 같은 이름의 구역 둘은 관객이 가를 수 없다.
     */
    ZONE_NAME_ALREADY_TAKEN("이미 있는 구역 이름입니다. 다른 이름을 입력해 주세요."),

    /** 구역 이름이 같은 도면의 블록 이름과 겹친다 — 블록 이름과 구역 이름은 서로 겹칠 수 없다(docs/02 "블록", #42). */
    ZONE_NAME_TAKEN_BY_BLOCK("이미 블록 이름으로 쓰고 있습니다. 다른 이름을 입력해 주세요."),

    /** 수량형 구역에 좌석을 배정하려 했다 — 수량형 구역에는 블록도 좌석도 없고 정원만 있다(docs/02 "설정 흐름"). */
    QUANTITY_ZONE_HAS_NO_SEATS("수량형 구역에는 좌석을 배정할 수 없습니다."),

    /** 이 행사의 도면에 없는 구역이다. */
    ZONE_NOT_FOUND("구역을 찾을 수 없습니다."),

    /** 이 행사의 도면에 없는 블록이다. */
    BLOCK_NOT_FOUND("블록을 찾을 수 없습니다."),

    /** 이 행사의 도면에 없는 좌석이다. */
    SEAT_NOT_FOUND("좌석을 찾을 수 없습니다."),

    /**
     * 확인 필요 (#37) — 같은 행사에 같은 이름의 입구가 이미 있다. 검표원이 고르는 목록과 게이트별 입장 현황이 이름으로 입구를 보여 주므로 같은 이름
     * 둘은 가를 수 없다(docs/02 "입구 (게이트)", docs/11).
     */
    ENTRANCE_NAME_ALREADY_TAKEN("이미 있는 입구 이름입니다. 다른 이름을 입력해 주세요."),

    /** 이 행사의 입구 목록에 없는 입구다. */
    ENTRANCE_NOT_FOUND("입구를 찾을 수 없습니다."),

    /** 작성 중이 아닌 행사의 판매를 시작하려 했다 — 판매 시작은 작성 중 → 판매 대기 전환이다(docs/04 "전환 트리거"). */
    SALES_ALREADY_STARTED("이미 판매를 시작한 행사입니다."),

    /**
     * 신규 개설 차단(정지 1단계 이상) 중인 주최자가 작성 중 행사의 판매를 시작하려 했다. 이미 판매 대기 · 판매 중인 행사는 그대로다(docs/01 "정지
     * 4단계").
     */
    SALES_START_BLOCKED_BY_SUSPENSION("주최자 정지 중에는 판매를 시작할 수 없습니다."),

    /** 행사 종료 · 취소됨이 아닌 행사를 정산 완료하려 했다 — 정산 완료는 행사 종료 또는 취소됨에서 관리자가 누른다(docs/04 "전환 트리거"). */
    SETTLEMENT_NOT_AVAILABLE("행사 종료 또는 취소된 행사만 정산 완료할 수 있습니다."),

    /**
     * 작성 중이거나 이미 끝난(행사 종료 · 정산 완료 · 취소됨) 행사의 회차를 취소하려 했다. 회차 취소 · 행사 취소는 시작하지 않은 회차가 있는 동안만
     * 한다(docs/04 "회차 취소", "행사 취소"). 작성 중 행사는 판 표가 없어 취소가 아니라 고치거나 지운다.
     */
    EVENT_NOT_CANCELLABLE("작성 중이거나 이미 끝난 행사는 취소할 수 없습니다."),

    /** 판매 중이 아닌 행사의 판매를 멈추려 했다 — 판매 중단은 "판매 중"의 변형이다(docs/04 "시간이 운영 판단을 이깁니다", "판매 중단"). */
    SALES_NOT_PAUSABLE("판매 중인 행사만 판매를 중단할 수 있습니다."),

    /** 이미 판매 중단인 행사의 판매를 또 멈추려 했다. 관리자 조치로 멈춘 행사도 이미 판매 중단이다. */
    SALES_ALREADY_PAUSED("이미 판매가 중단된 행사입니다."),

    /** 판매 중단이 아닌 행사의 판매를 재개하려 했다. */
    SALES_NOT_PAUSED("판매가 중단된 행사가 아닙니다."),

    /** 판매가 끝난 뒤(판매 종료 · 지난 행사) 재개하려 했다 — 판매 종료 이후에는 재개가 무의미해 재개 버튼이 사라진다(docs/04). */
    SALES_ALREADY_CLOSED("판매가 끝난 행사는 재개할 수 없습니다."),

    /**
     * 관리자 조치(정지 2단계 · 페이지 내리기)로 멈춘 판매를 주최자가 재개하려 했다. [재개]에 "관리자 조치로 중단됨"이 표시되고, 조치가 풀린 뒤에야
     * 주최자가 직접 재개한다(docs/01 "관리자가 멈춘 판매는 주최자가 풀 수 없습니다").
     */
    SALES_HELD_BY_ADMIN("관리자 조치로 중단된 판매입니다. 조치가 풀린 뒤 재개할 수 있습니다."),

    /**
     * 예매가 열린 뒤(판매 중 · 판매 중단) 바꿀 수 없는 항목을 바꾸려 했다 — 취소 · 환불 규정은 예매 시점 규정이 관객마다 따라다녀 바꿀 수 없다
     * (docs/04 "예매가 열린 뒤(판매 중) 수정 범위"). 표에 없어 막아 둔 항목도 여기다(확인 필요, {@link EventEditTarget}).
     */
    EDIT_LOCKED_AFTER_BOOKING_OPENED("예매가 열린 뒤에는 바꿀 수 없는 항목입니다."),

    /**
     * 예매가 열린 뒤 주최자가 장소를 혼자 바꾸려 했다 — 관리자 승인 + 전원 통지 + 공제 면제를 거친다(docs/04 "장소 변경"). 문구는 1단계 장소 입력
     * 경고(docs/03 "예매가 열린 뒤에는 장소를 혼자 바꿀 수 없습니다")에 맞췄다.
     */
    VENUE_CHANGE_NEEDS_ADMIN_APPROVAL("예매가 열린 뒤에는 장소를 혼자 바꿀 수 없습니다. 장소 변경 신청으로 관리자 승인을 받아 주세요."),

    /**
     * 판매가 끝난 뒤(판매 종료 ~ 행사 종료) 입구 목록 · 검표 계정 밖의 것을 바꾸려 했다 — 판매가 끝나면 현장이 이미 돌아가고 있어 현장 운영에 필요한
     * 것만 남긴다(docs/04 "판매 종료는 공연이 끝난 때가 아닙니다").
     */
    EDIT_LOCKED_AFTER_SALES_CLOSED("판매가 끝난 행사는 입구 목록과 검표 계정만 고칠 수 있습니다."),

    /** 지난 행사(행사 종료 · 정산 완료 · 취소됨)를 고치려 했다 — 전부 고정이고 복제는 된다(docs/04 "상태별로 할 수 있는 것", docs/13 "지난 행사"). */
    EDIT_LOCKED_FOR_PAST_EVENT("지난 행사는 고칠 수 없습니다. 복제해서 새 행사로 만들 수 있습니다."),

    /**
     * 예매가 열린 뒤 그 회차 시작 1주일 전이 지나 주최자가 혼자 회차 시간을 바꾸려 했다 — 이후는 관리자 승인을 거치는 연기 절차다(docs/04 "회차
     * 연기 — 1주일 전 잠금의 예외").
     */
    SESSION_TIME_EDIT_LOCKED("회차 시작 1주일 전부터는 회차 시간을 바꿀 수 없습니다. 연기 신청을 이용해 주세요.");

    private final String message;

    EventErrorCode(String message) {
        this.message = message;
    }

    @Override
    public String message() {
        return message;
    }
}
