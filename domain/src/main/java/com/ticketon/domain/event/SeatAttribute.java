package com.ticketon.domain.event;

/**
 * 좌석 속성 — 도면에 붙는 물리적 사실(docs/02 "좌석 속성", docs/14 "판매 제외는 회차 단위입니다"). 휠체어와 시야제한은 바뀌지 않는 사실이라 도면에
 * 붙는다. <b>판매 제외는 여기 없다</b> — 운영 판단이라 회차마다 다르고 재고가 회차를 가리켜 갖는다(#53). 첫 회차만 기자를 부르는 게 정상이라,
 * 도면 단위면 8회차 전부 빠진다.
 * <p>
 * 좌석 하나에 속성 하나다. 관객 화면의 안내 · 확인 체크(휠체어) · 동의(시야제한)는 예매 쪽이 이 속성을 보고 받는다(docs/02 "시야제한석 동의가
 * 중요합니다", "휠체어석은 체크박스 확인"). 동반석은 따로 정의하지 않는다 — 휠체어석 옆에 일반석을 두면 관객이 함께 고른다(docs/99 B).
 */
public enum SeatAttribute {

    /** 일반 — 기본. 새 좌석은 일반으로 생긴다. */
    GENERAL,

    /** 휠체어 — 배치도에 아이콘 + 색으로 가르고, 관객은 "휠체어 이용자용 좌석입니다"를 보고 확인 체크를 한다. */
    WHEELCHAIR,

    /** 시야제한 — 배치도에 색으로 가르고, 관객은 "무대 일부가 보이지 않을 수 있습니다"에 동의해야 고를 수 있다. */
    RESTRICTED_VIEW
}
