package com.ticketon.domain.event;

/**
 * 행사를 보여 주는 화면이 어느 쪽인가 — 관객 화면인가, 주최자 화면인가. 행사를 부르는 이름이 갈린다({@link EventType#nameOn}).
 * <p>
 * docs/00 "용어"는 이 두 쪽만 정한다. 관리자 · 검표 화면에서 행사를 무엇이라 부를지는 문서에 없어 여기 두지 않았다.
 */
public enum ScreenSide {

    /** 관객 화면 — 공개 영역(행사 목록 · 상세)과 관객 영역(예매 · 티켓). 행사를 유형 이름("공연" · "전시" · "페스티벌")으로 부른다. */
    AUDIENCE,

    /** 주최자 화면 — 주최 관리. 행사를 유형과 상관없이 전부 "행사"로 부른다. */
    ORGANIZER
}
