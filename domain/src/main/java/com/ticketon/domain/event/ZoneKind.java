package com.ticketon.domain.event;

/**
 * 구역의 종류 — 구역 안에 무엇이 있는가(docs/02 "구역"). 구역은 가격이 붙는 재고 묶음이고, 한 행사 안에서 두 종류를 섞을 수 있다("1층 스탠딩 +
 * 2층 좌석").
 * <pre>
 * 구역 추가
 *  ├─ 지정형 → 블록 배치 → 좌석 생성 → 구역 배정
 *  └─ 수량형 → 정원 입력만
 * </pre>
 */
public enum ZoneKind {

    /** 지정형 — 구역 안에 좌석이 하나하나 있고 관객이 자리를 고른다. 정원을 따로 받지 않는다 — 구역에 배정한 좌석이 곧 그 구역의 자리다. */
    DESIGNATED,

    /**
     * 수량형 — 구역 안에 정원 숫자만 있고 관객은 매수만 고른다. <b>블록도 좌석도 없다</b> — 번호를 매길 대상이 없다. 스탠딩 구역이 여러 개면 구역
     * 이름으로 나눈다("스탠딩A", "스탠딩B"). 티켓은 자리 대신 예매번호 + 순번으로 구분한다(docs/07 "티켓 표기").
     */
    QUANTITY
}
