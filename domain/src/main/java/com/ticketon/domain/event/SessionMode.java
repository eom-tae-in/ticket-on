package com.ticketon.domain.event;

/**
 * 회차 방식 — 회차형 / 종일형. 공연 · 전시 · 페스티벌을 고르는 유형({@link EventType})과는 다른 축이다. 회차형 전시도, 종일형 페스티벌도 있다
 * (docs/02 "회차형과 종일형 — 회차 방식"). 위저드 1단계가 아니라 회차를 만드는 2단계에서 고른다(docs/03 "기본 정보").
 * <p>
 * <b>기준은 재고가 시간 단위로 나뉘는가</b>이고, 날짜 아래 회차가 몇 개냐로 나타난다. 내용이 같은지 다른지가 아니다 — 회차마다 작품이 바뀌는
 * 연극제도 회차마다 좌석 재고가 따로 있으므로 회차형이다.
 * <table>
 *   <caption>회차형과 종일형</caption>
 *   <tr><th></th><th>회차형</th><th>종일형</th></tr>
 *   <tr><td>날짜 아래 회차</td><td>여러 개</td><td>하나</td></tr>
 *   <tr><td>예</td><td>공연, 시간대를 나눈 전시</td><td>전시, 페스티벌</td></tr>
 *   <tr><td>관객이 고르는 것</td><td>언제 들어갈지</td><td>며칠 갈지</td></tr>
 *   <tr><td>회차의 시간</td><td>시작(필수) · 종료(선택)</td><td>그날의 운영 시간 — 운영 시작~종료(필수) · 마지막 입장(선택)</td></tr>
 * </table>
 * <b>시간을 쪼개려면 회차형이다.</b> 종일형에는 시간대 분할이 없다 — 종일형의 정의가 "재고가 시간으로 나뉘지 않는 것"이라 시간대 분할은 정의와
 * 모순이었다(docs/02 "시간을 쪼개려면 회차형으로 등록합니다", docs/99 B "종일형 시간대 분할").
 * <p>
 * 이 상수 이름은 저장소에 그대로 남으므로 바꾸지 않는다.
 */
public enum SessionMode {

    /** 회차형 — 날짜 아래 회차가 여러 개. 회차마다 시작 시각(필수)과 종료 시각(선택)을 갖는다({@link TimedSessionTime}). */
    TIMED,

    /** 종일형 — 날짜 아래 회차가 하나. 회차의 시간은 그날의 운영 시간이다({@link OperatingHours}). */
    ALL_DAY
}
