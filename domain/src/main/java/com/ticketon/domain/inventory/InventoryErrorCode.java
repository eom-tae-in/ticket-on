package com.ticketon.domain.inventory;

import com.ticketon.domain.error.ErrorCode;

/**
 * 재고 도메인의 오류 코드. 문구는 화면에 그대로 나간다.
 */
public enum InventoryErrorCode implements ErrorCode {

    /**
     * 관객이 고른 좌석을 다른 요청이 먼저 잡았다 — 선점 중이거나 팔렸다. 먼저 도달한 쪽이 갖고 진 쪽에는 이 문구를 띄운다(docs/06 "두 사람이 동시에
     * 같은 자리를 눌렀다면"). 조용히 실패하면 관객이 계속 다시 누른다. 충돌({@link com.ticketon.domain.error.ConflictException})로 던진다.
     */
    SEAT_ALREADY_TAKEN("방금 다른 분이 선택했습니다"),

    /**
     * 확인 필요 (#53) — 판매 제외했거나 초대권이 걸린 좌석을 관객이 잡으려 했다. 판매 제외된 자리는 관객 화면에서 회색이고 선택이 안 된다(docs/09
     * "관계자석 확보"). 화면이 막지만 그 사이 주최자가 막 판매 제외한 경우가 있어, "다른 분이 선택했다"와 갈라 사실대로 알린다. 문구는 문서에 없다.
     */
    SEAT_NOT_FOR_SALE("판매하지 않는 좌석입니다."),

    /**
     * 팔렸거나 초대권이 나간 좌석을 판매 제외하려 했다 — 이미 팔린 좌석은 제외할 수 없다(docs/04 "예매가 열린 뒤 수정 범위" — 판매 제외 좌석). 초대권
     * 좌석도 받은 사람이 있는 자리라 팔린 좌석과 똑같이 지킨다(docs/04 "티켓"의 뜻).
     */
    TICKETED_SEAT_NOT_EXCLUDABLE("이미 팔렸거나 초대권이 나간 좌석은 판매 제외할 수 없습니다."),

    /**
     * 확인 필요 (#53) — 관객이 선점한 좌석을 판매 제외하려 했다. 문서에 없어 막아 둔다: 선점은 결제창까지 이어지고 "돈을 받았으면 좌석은 반드시
     * 준다"(docs/06)라, 결제 중인 자리를 빼면 관객이 낸 돈에 좌석을 줄 수 없다. 선점이 풀리면(최대 10분 + 결제 7분) 다시 할 수 있다.
     */
    HELD_SEAT_NOT_EXCLUDABLE("관객이 예매하고 있는 좌석이라 지금은 판매 제외할 수 없습니다. 잠시 뒤 다시 시도해 주세요."),

    /**
     * 초대권이 걸린 판매 제외 좌석의 판매 제외를 풀려 했다 — 초대권이 걸린 좌석은 판매 제외를 풀 수 없다(docs/04 "예매가 열린 뒤 수정 범위", docs/09
     * "오픈 전에 발권하면 그 초대권이 걸린 것은 잠깁니다"). 초대권을 회수하면 풀 수 있다.
     */
    INVITED_SEAT_EXCLUSION_LOCKED("초대권이 걸린 좌석은 판매 제외를 풀 수 없습니다."),

    /**
     * 그 회차의 예매가 마감되기 전에 판매 제외하지 않은 좌석에 초대권을 걸려 했다. 예매가 마감되기 전(오픈 전 포함)에는 관계자석(판매 제외)만 쓰고,
     * 마감된 뒤에는 안 팔린 일반 좌석도 쓴다(docs/09 "판매가 끝난 뒤에도 됩니다"). 문구는 문서에 없다 — 확인 필요 (#53).
     */
    INVITATION_NEEDS_EXCLUDED_SEAT("그 회차의 예매가 마감되기 전에는 판매 제외한 좌석에만 초대권을 발권할 수 있습니다."),

    /** 확인 필요 (#53) — 이미 팔렸거나, 선점 중이거나, 다른 초대권이 걸린 좌석에 초대권을 걸려 했다. 문구는 문서에 없다. */
    SEAT_TAKEN_FOR_INVITATION("이미 티켓이 걸렸거나 예매 중인 좌석이라 초대권을 발권할 수 없습니다."),

    /**
     * 지금 재고 상태에서 일어날 수 없는 변경 — 다른 선점의 좌석을 풀거나 확정하려 함, 팔리지 않은 좌석의 판매를 취소하려 함, 잡힌 수보다 많이 풀려 함
     * 등. 사람이 고른 조작이 아니라 선점 · 결제 · 취소 흐름이 어긋난 경우라 자세한 사정은 로그(detail)에만 남긴다.
     */
    INVENTORY_STATE_CHANGE_NOT_ALLOWED("지금 재고 상태에서는 할 수 없는 일입니다.");

    private final String message;

    InventoryErrorCode(String message) {
        this.message = message;
    }

    @Override
    public String message() {
        return message;
    }
}
