package com.ticketon.domain.booking;

/**
 * 관객 화면을 어떻게 열었는지 — 예매 자격 판정의 '미리보기 아님'을 본다(docs/03 "행사 만들기 위저드").
 * <p>
 * 운영진은 판매를 시작하기 전에 미리보기 링크로 관객 화면을 확인한다. <b>그 링크로는 예매가 되지 않는다</b> — 행사 상태와 상관없이 막는다.
 * 이 상수 이름은 화면과 주고받을 수 있으므로 바꾸지 않는다.
 */
public enum BookingAccess {

    /** 행사 페이지 — 공개 · 링크 전용 · 암호 보호를 지나 연 관객 화면, 마이페이지의 예매 카드. */
    EVENT_PAGE,

    /** 운영진의 관객 화면 미리보기 링크 — 예매되지 않는다. */
    PREVIEW_LINK
}
