package com.ticketon.domain.pricing;

/**
 * 티켓에 적용된 할인의 종류 — 없음 / 조기예매 / 쿠폰. 조기예매와 쿠폰은 중복되지 않아 티켓마다 하나다(docs/05 "할인 중복 규칙"). 자동으로 고르므로
 * 무엇이 적용됐는지 결제 내역에 보여 준다.
 * <p>
 * 회차별 조정과 묶음권 할인은 기본 가격을 정하는 단계라 여기 넣지 않는다.
 */
public enum DiscountKind {

    /** 할인 없음 — 기본 가격 그대로. */
    NONE,

    /** 조기예매 — 그 티켓이 조기예매 몫을 받았다. */
    EARLY_BIRD,

    /** 쿠폰 — 예매 건에 입력한 쿠폰. */
    COUPON
}
